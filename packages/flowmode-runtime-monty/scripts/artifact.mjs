import { readFile, copyFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";
const directory = new URL("../generated/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json", directory), "utf8"));
const executableNames = [
  "monty.component.js",
  "monty.component.core.wasm",
  "monty.component.core2.wasm",
  "monty.component.core3.wasm",
  "monty.component.core4.wasm",
];
if (
  JSON.stringify(Object.keys(manifest.artifacts).toSorted()) !==
    JSON.stringify(executableNames.toSorted()) ||
  !/^[a-f0-9]{40}$/.test(manifest.sourceCommit) ||
  !/^[a-f0-9]{64}$/.test(manifest.associationSha256) ||
  !Object.values(manifest.artifacts).every((hash) => /^[a-f0-9]{64}$/.test(hash))
) {
  throw Error("Invalid Monty executable manifest");
}
// Canonicalize the FULL manifest, including provenance and any future metadata.
function canonical(value) {
  if (Array.isArray(value)) {
    return value.map(canonical);
  }
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .toSorted()
        .map((key) => [key, canonical(value[key])]),
    );
  }
  return value;
}
const manifestDigest = createHash("sha256")
  .update(JSON.stringify(canonical(manifest)))
  .digest("hex");
const identitySource = `// Generated by scripts/artifact.mjs --generate; do not edit.\nexport const executableManifestDigest = "${manifestDigest}";\n`;
const identityFile = new URL("executable-identity.mjs", directory);
const associationBytes = await readFile(new URL("queues-association.json", directory));
if (createHash("sha256").update(associationBytes).digest("hex") !== manifest.associationSha256) {
  throw Error("Monty source association differs");
}
const association = JSON.parse(associationBytes.toString("utf8"));
// An explicit local checkout is required: this experimental commit is not published.
const generate = process.argv.includes("--generate");
const source = process.argv.slice(2).find((arg) => arg !== "--generate");
if (
  source &&
  execFileSync("git", ["-C", resolve(source), "rev-parse", "HEAD"], { encoding: "utf8" }).trim() !==
    manifest.sourceCommit
) {
  throw Error("Monty source commit differs");
}
if (source) {
  if (manifest.sourceState === "dirty") {
    const patch = execFileSync("git", ["-C", resolve(source), "diff", "--binary", "HEAD"]);
    if (createHash("sha256").update(patch).digest("hex") !== manifest.sourcePatchSha256) {
      throw Error("Monty dirty source patch differs");
    }
  } else {
    execFileSync("git", ["-C", resolve(source), "diff", "--quiet", "HEAD"]);
  }
  for (const [path, expected] of Object.entries({
    ...association.runtime,
    ...association.build_inputs,
  })) {
    const bytes = await readFile(resolve(source, path));
    if (createHash("sha256").update(bytes).digest("hex") !== expected) {
      throw Error(`Monty source input differs: ${path}`);
    }
  }
}
for (const [name, expected] of Object.entries(manifest.artifacts)) {
  const from = source
    ? resolve(source, "crates/monty-js/dist/worker/component", name)
    : new URL(name, directory);
  const bytes = await readFile(from);
  if (createHash("sha256").update(bytes).digest("hex") !== expected) {
    throw Error(`Monty artifact differs: ${name}`);
  }
  if (source) {
    await copyFile(from, new URL(name, directory));
  }
}
const { guestLibrary, demoSource, cleanupSource, errorSource } = await import("../src/guest.mjs");
for (const [file, text] of [
  ["workflow.py", guestLibrary],
  ["demo.py", demoSource],
  ["cleanup.py", cleanupSource],
  ["error.py", errorSource],
]) {
  if ((await readFile(new URL(`../guest/${file}`, import.meta.url), "utf8")) !== text) {
    throw Error(`Regenerate guest strings: ${file}`);
  }
}
if (generate) {
  await writeFile(identityFile, identitySource);
} else if ((await readFile(identityFile, "utf8")) !== identitySource) {
  throw Error(
    "Monty executable identity differs; run artifact.mjs --generate after reviewing the repin",
  );
}
console.log(
  `Monty artifacts verified: ${manifest.sourceCommit} (${manifest.sourceState ?? "clean"}); manifest SHA-256 ${manifestDigest}`,
);

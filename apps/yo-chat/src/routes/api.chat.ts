/**
 * Shared storage for durable streams.
 *
 * This is created once at module load time and persists across all HTTP requests.
 * This enables:
 * - Session reconnection (client can disconnect and reconnect to same session)
 * - Multi-client fan-out (multiple clients reading same session)
 * - Proper cleanup (sessions cleaned up when all clients disconnect AND stream completes)
 *
 * Storage strategy:
 * - REDIS_URL set → Redis-backed TokenBufferStore (durable across restarts)
 * - No REDIS_URL → In-memory shared storage (single-process only)
 */
const sharedStorage = createSharedStorage<string>()
const retainForeverPolicy: RetentionPolicy = { mode: 'retain_forever' }

// Initializer hook that uses Redis if available, otherwise in-memory shared storage
const setupDurableStreams = function* (): Operation<void> {
  const client = yield* call(() => getSharedRedisClient())

  if (client) {
    // Redis-backed TokenBufferStore with in-memory registry store
    const bufferStore = createRedisTokenBufferStore<string>(client)
    const registryStore = createInMemoryRegistryStore()
    yield* setupDurableStreamsWithConfig({
      bufferStore,
      registryStore,
      retentionPolicy: retainForeverPolicy,
    })
  } else {
    // In-memory shared storage
    const { bufferStore, registryStore } = getSharedStores(sharedStorage)
    yield* setupDurableStreamsWithConfig({
      bufferStore,
      registryStore,
      retentionPolicy: retainForeverPolicy,
    })
  }
}

function selectChatProvider(providerName: string): typeof ollamaProvider {
  const providerMap = {
    ollama: ollamaProvider,
    openai: openaiProvider,
  }

  const selectedProvider = providerMap[providerName as keyof typeof providerMap]
  if (!selectedProvider) {
    throw new Error(`Unknown provider: ${providerName}`)
  }
  return selectedProvider
}

const setupProvider = function* (ctx: InitializerContext): Operation<void> {
  // Dynamic runtime/provider selection based on request.
  // ProviderContext remains available for plugin sampling compatibility; model
  // execution is configured through RuntimeContext/RuntimeModelContext.
  const body = ctx.body as { provider?: string; model?: string }
  const providerName = body.provider || env.CHAT_PROVIDER
  yield* RuntimeContext.set(DefaultRuntime)
  yield* RuntimeModelContext.set(resolveRuntimeModel(providerName, body.model))
  yield* ProviderContext.set(selectChatProvider(providerName))
}


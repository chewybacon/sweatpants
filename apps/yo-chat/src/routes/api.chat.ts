/**
 * Sampling options interface (mirrors ToolSessionSamplingOptions)
 */
interface SamplingOptions {
  systemPrompt?: string
  maxTokens?: number
  tools?: SamplingToolDefinition[]
  toolChoice?: 'auto' | 'required' | 'none'
  schema?: Record<string, unknown>
}

interface ProviderStreamOptions {
  isomorphicToolSchemas?: Array<{
    name: string
    description: string
    parameters: Record<string, unknown>
    isIsomorphic: true
  }>
  toolChoice?: 'auto' | 'required' | 'none'
  schema?: Record<string, unknown>
}

/**
 * Real sampling provider for plugin tools.
 * 
 * This wraps the actual chat provider (Ollama/OpenAI) and:
 * 1. Converts SamplingToolDefinition[] to IsomorphicToolSchema[]
 * 2. Calls the provider's stream() method
 * 3. Collects the result and extracts toolCalls when present
 * 4. Returns properly typed SampleResultBase or SampleResultWithToolCalls
 */
function createPluginSamplingProvider(): ToolSessionSamplingProvider {
  // Determine which provider to use based on env
  const provider = selectChatProvider(env.CHAT_PROVIDER)
  
  return {
    *sample(messages: ExtendedMessage[], options: SamplingOptions | undefined) {
      // Convert SamplingToolDefinition[] to IsomorphicToolSchema[] format
      const isomorphicToolSchemas = options?.tools?.map((tool: SamplingToolDefinition) => ({
        name: tool.name,
        description: tool.description ?? '',
        parameters: typeof tool.inputSchema === 'object' && 'type' in tool.inputSchema
          ? tool.inputSchema as Record<string, unknown>
          : { type: 'object', properties: {}, required: [] }, // Fallback for Zod schemas (should be pre-converted)
        isIsomorphic: true as const,
      }))

      // Build provider options - only include isomorphicToolSchemas if tools were provided
      const streamOptions: ProviderStreamOptions = {}
      
      if (isomorphicToolSchemas && isomorphicToolSchemas.length > 0) {
        streamOptions.isomorphicToolSchemas = isomorphicToolSchemas
        // Pass through toolChoice if specified
        if (options?.toolChoice) {
          streamOptions.toolChoice = options.toolChoice
        }
      }

      // Pass through schema for structured output
      if (options?.schema) {
        streamOptions.schema = options.schema
      }

      // Convert ExtendedMessage[] to provider Message[] format
      const providerMessages: Message[] = messages.map(extendedMessageToProviderMessage)

      // Prepend system prompt as a system message if provided
      const messagesWithSystem: Message[] = options?.systemPrompt
        ? [{ id: 'system:plugin-sampling', role: 'system', content: options.systemPrompt }, ...providerMessages]
        : providerMessages

      // Call the provider's stream method and collect the result
      const stream = provider.stream(messagesWithSystem, streamOptions)
      
      // Consume the stream to get the final result
      let finalResult: ChatResult | undefined
      
      const subscription = yield* stream
      for (;;) {
        const next = yield* subscription.next()
        if (next.done) {
          finalResult = next.value
          break
        }
        // Ignore streaming events, we just want the final result
      }

      if (!finalResult) {
        return {
          text: '',
          model: provider.name,
          stopReason: 'error',
        } as SampleResultBase
      }

      // Check if the result has tool calls
      if (finalResult.toolCalls && finalResult.toolCalls.length > 0) {
        // Convert provider tool calls to SamplingToolCall format
        const samplingToolCalls: SamplingToolCall[] = finalResult.toolCalls.map((tc: NonNullable<ChatResult['toolCalls']>[number]) => ({
          id: tc.id,
          name: tc.function.name,
          arguments: tc.function.arguments,
        }))

        return {
          text: finalResult.text,
          model: provider.name,
          stopReason: 'toolUse',
          toolCalls: samplingToolCalls,
        } as SampleResultWithToolCalls
      }

      // Plain text result
      return {
        text: finalResult.text,
        model: provider.name,
        stopReason: 'endTurn',
      } as SampleResultBase
    },
  }
}

/**
 * Shared plugin session registry and manager (module-level, persists across requests).
 * 
 * CRITICAL: Both must be created in a long-lived Effection scope so that tool
 * sessions survive across HTTP request boundaries. This enables multi-step
 * elicitation flows where:
 * 
 * 1. Request 1: Tool starts, emits pickFlight elicitation, session stays alive
 * 2. Request 2: User selects flight, tool resumes from the same session
 * 3. Request 2: Tool emits pickSeat elicitation, session stays alive
 * 4. Request 3: User selects seat, tool completes
 * 
 * The manager wraps the registry and tracks:
 * - Session wrappers (for server-side sampling)
 * - Last processed LSN per session (to avoid replaying old events on reconnect)
 * 
 * This pattern mirrors how yo-mcp creates its registry at server startup.
 */
let sharedPluginSessionRegistry: ToolSessionRegistry | null = null
let sharedPluginSessionManager: PluginSessionManager | null = null

function* createLocalPluginToolSessionRegistry(): Operation<ToolSessionRegistry> {
  const store = createInMemoryToolSessionStore()
  const samplingProvider = createPluginSamplingProvider()
  // Worker URL provided by vite-plugin-node-worker
  // In dev: transpiles TS and rewrites imports to file:// URLs
  // In build: emits as separate chunk with proper relative path
  return yield* createToolSessionRegistry(store, {
    samplingProvider,
    worker: {
      workerUrl: toolWorkerUrl,
      isDev: process.env['NODE_ENV'] !== 'production',
    },
  })
}

function* createAgentCoreStores(): Operation<AgentCoreToolSessionStores> {
  const redis = yield* call(() => getSharedRedisClient())
  if (!redis) {
    return {
      handles: createInMemoryAgentCoreToolSessionHandleStore(),
      events: createInMemoryAgentCoreToolSessionEventStore(),
    }
  }

  const redisOptions = {
    keyPrefix: env.AGENTCORE_REDIS_KEY_PREFIX,
    defaultTtlSeconds: Math.max(1, Math.ceil(env.AGENTCORE_TOOL_SESSION_TTL_MS / 1000)),
  }
  const client = redis as unknown as RedisLikeClient
  return {
    handles: createRedisAgentCoreToolSessionHandleStore(client, redisOptions),
    events: createRedisAgentCoreToolSessionEventStore(client, redisOptions),
  }
}

function requireAgentCorePaidInvocationApproval(): void {
  if (process.env['APPROVE_AGENTCORE_PAID_INVOCATION'] !== 'yes') {
    throw new Error(
      'MCP_TOOL_RUNTIME=agentcore with AGENTCORE_RUNTIME_ARN may invoke paid AWS Bedrock AgentCore Runtime services. '
      + 'Set APPROVE_AGENTCORE_PAID_INVOCATION=yes for local/development app-mode AgentCore invocation.'
    )
  }
}

function* createAgentCorePluginToolSessionRegistry(): Operation<ToolSessionRegistry> {
  if (!env.AGENTCORE_RUNTIME_ARN) {
    throw new Error('AGENTCORE_RUNTIME_ARN is required when MCP_TOOL_RUNTIME=agentcore')
  }

  requireAgentCorePaidInvocationApproval()

  const toolNames = activeAgentCoreToolNames()
  if (toolNames.length === 0) {
    throw new Error('generated AgentCore tool registry must contain at least one tool when MCP_TOOL_RUNTIME=agentcore')
  }

  const stores = yield* createAgentCoreStores()
  const runtimeClient = createAgentCoreRemoteToolRuntimeClient(
    createAwsSdkAgentCoreInvoker({ clientConfig: { region: env.AGENTCORE_REGION } })
  )
  const profile: AgentCoreToolRuntimeProfile = {
    name: env.AGENTCORE_RUNTIME_PROFILE_NAME,
    runtimeArn: env.AGENTCORE_RUNTIME_ARN,
    endpointName: env.AGENTCORE_ENDPOINT_NAME,
    region: env.AGENTCORE_REGION,
    toolNames,
    maxSessionTtlMs: env.AGENTCORE_TOOL_SESSION_TTL_MS,
  }

  return createAgentCoreToolSessionRegistry({
    stores,
    runtimeClient,
    profiles: [profile],
    defaultProfile: profile.name,
  })
}

function redactAgentCoreArn(value: string | undefined): string | undefined {
  if (!value) return undefined
  const suffix = value.split('/').pop()?.slice(-8) ?? 'unknown'
  return `[redacted-agentcore-runtime:${suffix}]`
}

function* createConfiguredPluginToolSessionRegistry(): Operation<ToolSessionRegistry> {
  if (env.MCP_TOOL_RUNTIME === 'agentcore') {
    console.info('[yo-chat] MCP tool runtime: agentcore', {
      runtimeArn: redactAgentCoreArn(env.AGENTCORE_RUNTIME_ARN),
      endpointName: env.AGENTCORE_ENDPOINT_NAME,
      region: env.AGENTCORE_REGION,
      toolNames: activeAgentCoreToolNames(),
    })
    return yield* createAgentCorePluginToolSessionRegistry()
  }

  console.info('[yo-chat] MCP tool runtime: local')
  return yield* createLocalPluginToolSessionRegistry()
}

// Create the registry and manager in a long-lived scope at module initialization.
// This runs once when the module is first imported.
const registryPromise = run(function* () {
  const registry = yield* createConfiguredPluginToolSessionRegistry()
  const manager = yield* createPluginSessionManager({ registry })
  sharedPluginSessionRegistry = registry
  sharedPluginSessionManager = manager
  return { registry, manager }
})

const setupPlugins = function* (_ctx: InitializerContext): Operation<void> {
  yield* PluginRegistryContext.set(pluginRegistry)
  yield* McpToolRegistryContext.set(mcpToolRegistry)

  // Wait for registry and manager to be ready. They are created at module load,
  // but the first HTTP request can race initialization in dev/serverless mode.
  if (!sharedPluginSessionRegistry || !sharedPluginSessionManager) {
    const ready = yield* call(() => registryPromise)
    sharedPluginSessionRegistry = ready.registry
    sharedPluginSessionManager = ready.manager
  }

  yield* PluginSessionRegistryContext.set(sharedPluginSessionRegistry)
  yield* PluginSessionManagerContext.set(sharedPluginSessionManager)
}

